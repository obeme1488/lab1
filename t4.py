#завадння 4. множини

def main():
    #вхідні списки ідентифікаторів (з повторами)
    list_a = [1, 2, 2, 3, 4, 5, 5]
    list_b = [4, 5, 6, 7, 7, 8]
    list_c = [1, 2]  #для перевірки підмножини

    print(f"список а: {list_a}")
    print(f"список б: {list_b}")
    print(f"список в: {list_c}")

    #перетворюємо списки на множини (залишаються лише унікальні)
    set_a = set(list_a)
    set_b = set(list_b)
    set_c = set(list_c)

    print("\nунікальні значення (множини):")
    print(f"множина а: {set_a}")
    print(f"множина б: {set_b}")

    #базові операції над множинами
    print("\nоперації:")

    #перетин(спільні елементи)
    intersect = set_a & set_b
    print(f"перетин (а і б): {intersect}")

    #об'єднання(всі унікальні елементи з обох)
    union_set = set_a | set_b
    print(f"об'єднання (а або б): {union_set}")

    #симетрична різниця (тільки ті, що є в одній множині, але не в обох)
    sym_diff = set_a ^ set_b
    print(f"симетрична різниця: {sym_diff}")

    #перевірка на підмножину
    print("\nперевірка підмножини:")

    is_sub_c_a = set_c <= set_a
    print(f"чи є 'в' підмножиною 'а'? {is_sub_c_a}")

    is_sub_b_a = set_b <= set_a
    print(f"чи є 'б' підмножиною 'а'? {is_sub_b_a}")


if __name__ == "__main__":
    main()